    private void btn_authenActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_authenActionPerformed
        // TODO add your handling code here:
        if (!ConnectCardUtils.isConnected()) {
            JOptionPane.showMessageDialog(null, "Vui lòng connect với card trước khi gửi lệnh");
            System.out.println("Vui long connect truoc khi gui lenh");
            return;
        }
        String pin = txt_pin_code.getText();
        if (pin == null) {
            JOptionPane.showMessageDialog(null, "Vui long nhap ma pin");
            return;
        }
        boolean status = ConnectCardUtils.authenPin(pin);
        if (status) {
            countAuthenCard = 0;
            readInforCard();
        } else {
            countAuthenCard++;
            if (countAuthenCard >= 3) {
                JOptionPane.showMessageDialog(null, "Đã sai quá 3 lần, vui lòng mở khóa thẻ để tiếp tục");
                btn_authen.setEnabled(false);
            }

        }

    }//GEN-LAST:event_btn_authenActionPerformed

