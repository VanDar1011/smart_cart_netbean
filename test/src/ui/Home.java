    private void readInforCard() {
        // infort
        try {
            byte[] result = ConnectCardUtils.sendApduHaveResponse(CommandDefine.GET_INFOR_CARD);
            String hexResult = StringUtils.bytesToHex(result); // Assuming you have this utility method
            System.out.println("Hex Result Length: " + hexResult.length());
            byte[] hexa = StringUtils.hexStringToByteArray(hexResult);
            System.out.println("Hexa : " + hexa);
            List<byte[]> parts = StringUtils.splitHexArrayBySemicolon(hexa);
            System.out.println("Parts : " + parts);
            txt_employee_code.setText(StringUtils.hexArrayToText(parts.get(0)));
            txt_name.setText(StringUtils.hexArrayToText(parts.get(1)));
            txt_birthday.setText(StringUtils.hexArrayToText(parts.get(2)));
            txt_position.setText(StringUtils.hexArrayToText(parts.get(3)));
            String status;
            if (parts.get(4).length == 1 && parts.get(4)[0] == 0x00) {
                status = "active";
            } else {
                btn_authen.setEnabled(false);
                status = "deactive";
            }
            txt_status.setText(status);
//            txt_pin.setText(StringUtils.hexArrayToText(parts.get(5)));
            // image
            byte[] image = ConnectCardUtils.sendApduHaveResponse(CommandDefine.GET_IMG);
            if (image.length > 0) {
                System.out.println("Do lon lon hon khonog");
                ImageUtils.displayImage(image, label_img);
            }

        } catch (Exception e) {
            System.out.println("Exception : " + e.getMessage());
        }

    }

